"""
TrustForge — Metrics Service (Research Evaluation Harness)

Loads evaluation cases, runs the scanner, computes classification metrics.
Ground truth is manually prepared — never generated by the algorithm being evaluated.

Metrics computed:
  Binary detection tasks: TP, FP, TN, FN, Precision, Recall, F1, Accuracy
  
Ground truth labels in evaluation cases are described as
"manually prepared reference labels" — they were NOT produced by TrustForge.
"""
from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from app.config import settings


# Fields compared in evaluation (binary detection)
BINARY_FIELDS = [
    "privacy_policy_found",
    "https_detected",
    "consent_banner_detected",
    "reject_button_detected",
    "grievance_contact_detected",
]


def _load_evaluation_cases() -> list[dict]:
    """Load all evaluation cases from the cases directory."""
    cases_path = Path(settings.evaluation_cases_path)
    if not cases_path.exists():
        return []
    cases = []
    for f in sorted(cases_path.glob("*.json")):
        try:
            with open(f, encoding="utf-8") as fp:
                cases.append(json.load(fp))
        except Exception:
            pass
    return cases


def _predict_from_html(html_path: str) -> dict:
    """
    Run the scanner's detection logic on a local HTML fixture file.
    Returns predictions for each binary field.
    """
    from bs4 import BeautifulSoup
    from app.services.website_scanner import (
        _detect_cookie_consent, _detect_trackers, PRIVACY_URL_PATTERNS, GRIEVANCE_PATTERNS
    )

    try:
        html = Path(html_path).read_text(encoding="utf-8", errors="replace")
    except FileNotFoundError:
        return {field: None for field in BINARY_FIELDS}

    soup = BeautifulSoup(html, "lxml")
    text_lower = html.lower()

    # Privacy policy
    privacy_found = any(
        any(p in (a.get("href", "") + " " + a.get_text()).lower() for p in PRIVACY_URL_PATTERNS)
        for a in soup.find_all("a", href=True)
    )

    # HTTPS — fixture check (check if it's in HTML tags)
    https_detected = "https://" in text_lower

    # Consent
    from app.services.website_scanner import CONSENT_PATTERNS, CONSENT_REJECT_PATTERNS
    consent_detected = any(p in text_lower for p in CONSENT_PATTERNS)
    reject_detected = any(p in text_lower for p in CONSENT_REJECT_PATTERNS)

    # Grievance contact
    grievance_detected = any(p in text_lower for p in GRIEVANCE_PATTERNS)

    return {
        "privacy_policy_found": privacy_found,
        "https_detected": https_detected,
        "consent_banner_detected": consent_detected,
        "reject_button_detected": reject_detected,
        "grievance_contact_detected": grievance_detected,
    }


def _compute_binary_metrics(
    predictions: list[Optional[bool]],
    ground_truths: list[Optional[bool]],
) -> dict:
    """Compute TP/FP/TN/FN and derived metrics for a set of binary predictions."""
    tp = fp = tn = fn = 0
    for pred, gt in zip(predictions, ground_truths):
        if pred is None or gt is None:
            continue
        if pred and gt:
            tp += 1
        elif pred and not gt:
            fp += 1
        elif not pred and not gt:
            tn += 1
        else:
            fn += 1

    total = tp + fp + tn + fn
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) > 0 else 0.0
    accuracy = (tp + tn) / total if total > 0 else 0.0

    return {
        "true_positives": tp,
        "false_positives": fp,
        "true_negatives": tn,
        "false_negatives": fn,
        "precision": round(precision, 3),
        "recall": round(recall, 3),
        "f1_score": round(f1, 3),
        "accuracy": round(accuracy, 3),
        "evaluated_pairs": total,
    }


def run_evaluation_harness() -> dict:
    """
    Run the full evaluation harness:
    1. Load cases
    2. Run predictions
    3. Compare to ground truth
    4. Compute metrics
    5. Save results
    """
    import time
    start = time.time()
    cases = _load_evaluation_cases()

    if not cases:
        return {
            "status": "no_cases",
            "message": (
                "No evaluation cases found. "
                "Add case files to the evaluation/cases/ directory."
            ),
        }

    all_preds: dict[str, list] = {field: [] for field in BINARY_FIELDS}
    all_gts: dict[str, list] = {field: [] for field in BINARY_FIELDS}
    per_case_results = []

    for case in cases:
        case_id = case.get("case_id", "unknown")
        gt = case.get("ground_truth", {})
        html_fixture = case.get("html_fixture_path")

        if html_fixture:
            preds = _predict_from_html(html_fixture)
        else:
            # Cannot evaluate without fixture or URL scan
            preds = {field: None for field in BINARY_FIELDS}

        case_result = {"case_id": case_id, "predictions": preds, "ground_truth": gt}

        for field in BINARY_FIELDS:
            pred_val = preds.get(field)
            gt_val = gt.get(field)
            all_preds[field].append(pred_val)
            all_gts[field].append(gt_val)

        per_case_results.append(case_result)

    # Overall metrics across all fields and cases
    flat_preds = []
    flat_gts = []
    for field in BINARY_FIELDS:
        flat_preds.extend(all_preds[field])
        flat_gts.extend(all_gts[field])

    overall_metrics = _compute_binary_metrics(flat_preds, flat_gts)

    # Per-field metrics
    per_field_metrics = {}
    for field in BINARY_FIELDS:
        per_field_metrics[field] = _compute_binary_metrics(all_preds[field], all_gts[field])

    run_id = uuid.uuid4().hex[:8]
    result = {
        "run_id": run_id,
        "run_date": datetime.now(timezone.utc).isoformat(),
        "total_cases": len(cases),
        "fields_evaluated": BINARY_FIELDS,
        "overall_metrics": overall_metrics,
        "per_field_metrics": per_field_metrics,
        "per_case_results": per_case_results,
        "elapsed_seconds": round(time.time() - start, 2),
        "note": (
            "Ground truth labels were manually prepared by the researcher. "
            "These are 'manually prepared reference labels', NOT expert-validated or auto-generated."
        ),
    }

    # Save results
    results_path = Path(settings.research_results_path)
    results_path.mkdir(parents=True, exist_ok=True)
    output_file = results_path / f"scanner_metrics_{run_id}.json"
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, ensure_ascii=False)

    result["saved_to"] = str(output_file)
    return result


def load_last_results() -> dict:
    """Load the most recently saved evaluation results."""
    results_path = Path(settings.research_results_path)
    if not results_path.exists():
        return {"status": "no_results", "message": "No evaluation results found. Run POST /api/evaluation/run first."}

    result_files = sorted(results_path.glob("scanner_metrics_*.json"), reverse=True)
    if not result_files:
        return {"status": "no_results", "message": "No evaluation results found."}

    with open(result_files[0], encoding="utf-8") as f:
        return json.load(f)
