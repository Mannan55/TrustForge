"""
TrustForge — Research Evaluation Runner

Usage:
    cd TrustForgeV4/backend
    python run_evaluation.py

This script:
1. Loads evaluation cases from evaluation/cases/
2. Runs TrustForge scanner predictions on HTML fixtures
3. Compares predictions to ground truth labels
4. Computes Precision, Recall, F1, Accuracy
5. Saves results to research/results/
6. Prints a summary table

Research Note:
  Ground truth labels are manually prepared reference labels.
  They were NOT generated by TrustForge or any automated algorithm.
  This is required for valid research evaluation.

Reproducibility:
  Running this script with the same evaluation cases and TrustForge version
  should produce identical results.
"""
import sys
import json
from pathlib import Path

# Add backend to path
sys.path.insert(0, str(Path(__file__).parent))

from app.config import settings
from app.services.metrics_service import run_evaluation_harness


def print_table(title: str, data: dict, indent: int = 2):
    print("\n" + " " * indent + f"{'─' * 50}".encode('ascii', 'replace').decode())
    print(" " * indent + title)
    print(" " * indent + f"{'─' * 50}")
    for k, v in data.items():
        if isinstance(v, float):
            print(f"  {k:<35} {v:.3f}")
        else:
            print(f"  {k:<35} {v}")


def main():
    print("\n" + "=" * 60)
    print("  TrustForge Research Evaluation Harness")
    print(f"  Scoring Version: {settings.scoring_version}")
    print("=" * 60)

    print("\n[1/3] Loading evaluation cases...")
    results = run_evaluation_harness()

    if results.get("status") == "no_cases":
        print(f"\n  WARNING: {results['message']}")
        print("\n  To add evaluation cases:")
        print("  1. Add case JSON files to: backend/evaluation/cases/")
        print("  2. Add HTML fixtures to:   backend/evaluation/fixtures/")
        print("  3. Re-run this script.")
        return

    print(f"  Cases loaded: {results['total_cases']}")

    print("\n[2/3] Running predictions on HTML fixtures...")
    print(f"  Fields evaluated: {', '.join(results['fields_evaluated'])}")

    print("\n[3/3] Computing metrics...")

    # Overall metrics
    print_table("OVERALL METRICS (All Fields + All Cases)", results["overall_metrics"])

    # Per-field breakdown
    print("\n  Per-Field Detection Accuracy:")
    print(f"  {'Field':<35} {'Precision':>10} {'Recall':>10} {'F1':>10} {'Accuracy':>10}")
    print(f"  {'─' * 80}")
    for field, metrics in results.get("per_field_metrics", {}).items():
        if metrics.get("evaluated_pairs", 0) == 0:
            print(f"  {field:<35} {'N/A':>10} {'N/A':>10} {'N/A':>10} {'N/A':>10}")
        else:
            print(
                f"  {field:<35}"
                f" {metrics['precision']:>10.3f}"
                f" {metrics['recall']:>10.3f}"
                f" {metrics['f1_score']:>10.3f}"
                f" {metrics['accuracy']:>10.3f}"
            )

    # Case summary
    print(f"\n  Per-Case Results:")
    for case in results.get("per_case_results", []):
        print(f"    Case {case['case_id']}: predictions={case['predictions']}")

    # Note
    print(f"\n  NOTE: {results.get('note', '')}")
    print(f"\n  Results saved to: {results.get('saved_to', 'research/results/')}")
    print(f"  Run ID: {results.get('run_id')}")
    print(f"  Elapsed: {results.get('elapsed_seconds')}s")
    print("\n" + "=" * 60)
    print("  Evaluation complete. Results saved for research paper.")
    print("=" * 60 + "\n")


if __name__ == "__main__":
    main()
